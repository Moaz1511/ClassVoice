"""Private generated-audio asset records and storage-backed output sink."""

from __future__ import annotations

import asyncio
import hashlib
from collections.abc import Mapping
from dataclasses import dataclass
from datetime import UTC, datetime
from typing import Literal, Protocol
from uuid import UUID, uuid4

from app.inference.adapter import InferenceResult
from app.storage.ports import StorageAdapter, StorageError

from .jobs import GenerationJob

GenerationOutputFormat = Literal["wav", "mp3"]


class GenerationOutputError(RuntimeError):
    """A safe, retry-aware failure while creating a private output asset."""

    def __init__(self, code: str, message: str, *, retryable: bool = True) -> None:
        super().__init__(message)
        self.code = code
        self.retryable = retryable


@dataclass(frozen=True, slots=True)
class GenerationOutput:
    """Metadata persisted beside one private generated-audio object."""

    id: UUID
    generation_job_id: UUID
    workspace_id: UUID
    bucket: str
    object_key: str
    output_format: GenerationOutputFormat
    content_type: str
    byte_size: int
    duration_ms: int
    checksum_sha256: str
    provenance: Mapping[str, object]
    created_at: datetime

    def as_dict(self) -> dict[str, object]:
        """Return API-safe metadata without exposing the private object key."""

        return {
            "id": str(self.id),
            "generation_job_id": str(self.generation_job_id),
            "output_format": self.output_format,
            "content_type": self.content_type,
            "byte_size": self.byte_size,
            "duration_ms": self.duration_ms,
            "checksum_sha256": self.checksum_sha256,
            "provenance": dict(self.provenance),
            "created_at": self.created_at.isoformat(),
        }


class GenerationOutputSink(Protocol):
    async def put(self, job: GenerationJob, result: InferenceResult) -> object: ...


class PrivateGenerationOutputStore:
    """Upload generated bytes to a private bucket and retain output metadata.

    The metadata map is intentionally process-local until the SQL repository
    wiring is completed.  The object itself is written through the production
    ``StorageAdapter`` boundary, so the same authorization and private-bucket
    contract applies to LocalStack, S3, and Supabase.
    """

    def __init__(self, storage: StorageAdapter, *, bucket: str = "generated-audio") -> None:
        self._storage = storage
        self._bucket = bucket
        self._outputs: dict[UUID, GenerationOutput] = {}
        self._job_locks: dict[UUID, asyncio.Lock] = {}
        self._lock = asyncio.Lock()

    async def put(self, job: GenerationJob, result: InferenceResult) -> GenerationOutput:
        output_format = _format_for_result(result)
        if output_format != job.output_format:
            raise GenerationOutputError(
                "OUTPUT_FORMAT_MISMATCH",
                "The generated output format does not match the job request.",
                retryable=False,
            )
        checksum = hashlib.sha256(result.audio_bytes).hexdigest()
        if checksum != result.sha256:
            raise GenerationOutputError(
                "OUTPUT_CHECKSUM_MISMATCH",
                "The generated output checksum could not be verified.",
                retryable=False,
            )
        if not result.audio_bytes or len(result.audio_bytes) > 25_000_000:
            raise GenerationOutputError(
                "OUTPUT_SIZE_INVALID",
                "The generated output exceeds the private asset size limit.",
                retryable=False,
            )
        if result.duration_ms <= 0 or result.duration_ms > 120_000:
            raise GenerationOutputError(
                "OUTPUT_DURATION_INVALID",
                "The generated output exceeds the duration limit.",
                retryable=False,
            )

        extension = "mp3" if output_format == "mp3" else "wav"
        object_key = f"{job.workspace_id}/{job.id}/{checksum}.{extension}"
        job_lock = await self._lock_for(job.id)
        async with job_lock:
            existing = await self.get(job.id)
            if existing is not None:
                if (
                    existing.checksum_sha256 == checksum
                    and existing.output_format == output_format
                    and existing.content_type == result.content_type
                ):
                    return existing
                raise GenerationOutputError(
                    "OUTPUT_ALREADY_COMMITTED",
                    "A different generated output is already committed for this job.",
                    retryable=False,
                )
            try:
                await self._storage.put_object(
                    self._bucket,
                    object_key,
                    result.audio_bytes,
                    content_type=result.content_type,
                )
            except StorageError as error:
                raise GenerationOutputError(
                    "STORAGE_WRITE_FAILED",
                    "The generated audio could not be stored privately.",
                    retryable=True,
                ) from error

            provenance = dict(result.metadata)
            provenance.update(
                {
                    "generation_job_id": str(job.id),
                    "model_key": job.model_key,
                    "model_version": job.model_version,
                    "checkpoint_sha256": job.checkpoint_sha256,
                    "output_sha256": checksum,
                    "output_format": output_format,
                }
            )
            output = GenerationOutput(
                id=uuid4(),
                generation_job_id=job.id,
                workspace_id=job.workspace_id,
                bucket=self._bucket,
                object_key=object_key,
                output_format=output_format,
                content_type=result.content_type,
                byte_size=len(result.audio_bytes),
                duration_ms=result.duration_ms,
                checksum_sha256=checksum,
                provenance=provenance,
                created_at=datetime.now(UTC),
            )
            async with self._lock:
                self._outputs[job.id] = output
            return output

    async def get(self, job_id: UUID) -> GenerationOutput | None:
        async with self._lock:
            return self._outputs.get(job_id)

    async def _lock_for(self, job_id: UUID) -> asyncio.Lock:
        async with self._lock:
            return self._job_locks.setdefault(job_id, asyncio.Lock())


def _format_for_result(result: InferenceResult) -> GenerationOutputFormat:
    if result.content_type == "audio/wav":
        return "wav"
    if result.content_type == "audio/mpeg":
        return "mp3"
    raise GenerationOutputError(
        "OUTPUT_CONTENT_TYPE_INVALID",
        "The generated output content type is unsupported.",
        retryable=False,
    )
